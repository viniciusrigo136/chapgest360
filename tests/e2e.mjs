// Teste de ponta a ponta no "modo local", simulando um celular.
// Uso: npm run build && npx vite preview --port 4173 & node tests/e2e.mjs
import { createRequire } from 'node:module'
const { chromium, devices } = createRequire(import.meta.url)('playwright')
import { mkdirSync } from 'node:fs'

const BASE = process.env.BASE ?? 'http://localhost:4173'
const OUT = process.env.OUT ?? 'test-results'
mkdirSync(OUT, { recursive: true })
const browser = await chromium.launch()
const ctx = await browser.newContext({ ...devices['Pixel 7'], locale: 'pt-BR', timezoneId: 'America/Sao_Paulo' })
await ctx.addInitScript(() => { try { localStorage.setItem('lataria-resumo', 'nunca') } catch {} })
const page = await ctx.newPage()
const errors = []
page.on('pageerror', (e) => errors.push(e.message))
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()))
page.on('dialog', (d) => d.accept())
const shot = (name) => page.screenshot({ path: `${OUT}/${name}.png`, fullPage: true })
const step = (s) => console.log('•', s)

try {
await page.goto(BASE + '/config')
if (await page.getByRole('button', { name: 'Entrar' }).isVisible().catch(() => false)) {
  step('criar conta e oficina (modo nuvem)')
  await page.getByRole('button', { name: /Criar conta/ }).click()
  await page.getByLabel('E-mail').fill(`teste${Date.now()}@exemplo.com`)
  await page.getByLabel('Senha').fill('senha-forte-123')
  await page.getByRole('button', { name: 'Criar conta' }).click()
  await page.getByText('Qual o nome da sua oficina?').waitFor()
  await page.getByRole('textbox').fill('Funilaria Exemplo')
  await page.getByRole('button', { name: 'Continuar' }).click()
  await page.getByLabel('Nome fantasia *').waitFor()
}
step('configurações da empresa')
await page.getByLabel('Nome fantasia *').fill('Funilaria Exemplo')
await page.getByLabel('Especialidade / slogan').fill('Funilaria • Pintura • Polimento')
await page.getByLabel('WhatsApp', { exact: true }).fill('11988887777')
await page.getByLabel('Cidade', { exact: true }).fill('São Paulo')
await page.getByLabel('Chave PIX').fill('pix@exemplo.com')
await page.getByRole('button', { name: 'Salvar configurações' }).click()
await page.getByText('Configurações salvas').waitFor()
await shot('01-config')

step('novo orçamento com cliente e veículo criados na hora')
await page.goto(BASE + '/orcamentos/novo')
await page.getByText('Escolher cliente e carro').click()
await page.getByRole('button', { name: 'Novo cliente' }).click()
await page.getByLabel('Nome ou razão social *').fill('Maria Souza')
await page.getByLabel('Telefone / WhatsApp').fill('11999990000')
await page.getByRole('button', { name: 'Salvar cliente' }).click()
await page.getByLabel('Placa *').fill('abc1d23')
await page.getByLabel('Marca', { exact: true }).fill('VW')
await page.getByLabel('Modelo', { exact: true }).fill('Gol')
await page.getByLabel('Cor', { exact: true }).fill('Prata')
await page.getByRole('button', { name: 'Salvar carro' }).click()
await page.getByText('Maria Souza').first().waitFor()

for (const [desc, price] of [['Pintura do para-choque dianteiro', '850,00'], ['Reparo da porta dianteira esquerda', '1.200,00']]) {
  await page.getByLabel('Serviço ou peça').fill(desc)
  await page.getByLabel('Valor do item').fill(price)
  await page.getByRole('button', { name: 'Adicionar' }).click()
}
await page.getByText('Mais opções').click()
await page.getByRole('button', { name: 'É serviço de seguradora' }).click()
await page.getByLabel('Seguradora', { exact: true }).fill('Porto Seguro')
await page.getByLabel('Nº do sinistro').fill('123456')
await page.getByLabel('Franquia').fill('500,00')
await page.locator('input[type=file][multiple]').setInputFiles(['tests/fixtures/carro.png', 'tests/fixtures/carro.png'])
await page.getByRole('button', { name: /Galeria/ }).waitFor()
await page.waitForFunction(() => document.querySelectorAll('section img').length >= 2, null, { timeout: 30000 })
await page.getByLabel('Parcelas').selectOption('3')
await shot('02-orcamento-editor')
await page.getByRole('button', { name: 'Salvar', exact: true }).click()
await page.waitForURL(/\/orcamentos\/[0-9a-f-]{36}$/)
await page.getByText('R$ 2.050,00').first().waitFor()
await shot('03-orcamento-view')
const quoteUrl = page.url()

step('link público + QR')
await page.getByRole('button', { name: 'Enviar ao cliente' }).click()
const waHref = await page.getByRole('link', { name: 'Enviar pelo WhatsApp' }).getAttribute('href')
if (!waHref.startsWith('https://wa.me/5511999990000?text=')) throw new Error('link do WhatsApp errado: ' + waHref)
const publicHref = await page.getByRole('link', { name: /Ver como cliente/ }).getAttribute('href')
await shot('04-compartilhar')
await page.getByRole('button', { name: 'Fechar' }).click()

step('impressão A4')
await page.getByRole('link', { name: 'PDF', exact: true }).click()
await page.getByRole('button', { name: 'Imprimir / Salvar PDF' }).waitFor()
await shot('05-impressao-celular')
await page.emulateMedia({ media: 'print' })
await page.pdf({ path: `${OUT}/orcamento.pdf`, preferCSSPageSize: true, printBackground: true })
await page.emulateMedia({ media: 'screen' })

step('cliente aprova pelo link (outro aparelho)')
const pub = await ctx.newPage()
await pub.goto(publicHref)
await pub.getByText('Aguardando sua aprovação').waitFor()
await pub.screenshot({ path: `${OUT}/06-cliente-orcamento.png`, fullPage: true })
await pub.getByPlaceholder('Seu nome completo').fill('Maria Souza')
await pub.getByRole('button', { name: 'Aprovar orçamento' }).click()
await pub.getByText(/Respondido por Maria Souza/).waitFor()

step('transformar em OS')
await page.goto(quoteUrl)
await page.getByText('Aprovado').first().waitFor()
await page.getByRole('button', { name: /abrir serviço/ }).click()
await page.waitForURL(/\/os\/[0-9a-f-]{36}$/)
const osUrl = page.url()
await page.getByRole('button', { name: /Avançar para: Avaliação/ }).click()
await page.getByRole('button', { name: 'Agora não' }).click()
await page.getByRole('button', { name: 'Receber pagamento' }).click()
await page.getByRole('textbox', { name: /^Valor/ }).fill('500,00')
await page.getByRole('button', { name: /^Registrar/ }).click()
await page.getByText('Pagamento registrado').waitFor()

step('checklist opcional com desenho do carro')
await page.goto(osUrl + '/editar')
await page.getByText('Mais opções').click()
await page.getByRole('button', { name: 'Fazer checklist do carro' }).click()
await page.getByLabel('Km na entrada').fill('85000')
await page.locator('svg g', { hasText: 'Porta diant. esq.' }).click()
await page.getByRole('button', { name: 'Amassado' }).click()
await page.getByRole('button', { name: 'Estepe' }).click()
await shot('07-checklist')
await page.getByRole('button', { name: 'Salvar', exact: true }).click()
await page.waitForURL(osUrl)
await page.getByText('Checklist de entrada').waitFor()
await shot('08-os-view')

step('página do cliente da OS')
await page.getByRole('button', { name: 'Link do cliente' }).click()
const osLink = await page.getByRole('link', { name: /Ver como cliente/ }).getAttribute('href')
await page.getByRole('button', { name: 'Fechar' }).click()
await pub.goto(osLink)
await pub.getByText('Etapa atual').waitFor()
await pub.screenshot({ path: `${OUT}/09-cliente-os.png`, fullPage: true })
await pub.goto(osLink.replace(/[^/]+$/, 'token-que-nao-existe-xxxxxx'))
await pub.getByText('Link indisponível').waitFor()

step('impressão da OS')
await page.goto(osUrl.replace('/os/', '/imprimir/work_order/'))
await page.getByRole('button', { name: 'Imprimir / Salvar PDF' }).waitFor()
await page.emulateMedia({ media: 'print' })
await page.pdf({ path: `${OUT}/os.pdf`, preferCSSPageSize: true, printBackground: true })
await page.emulateMedia({ media: 'screen' })

step('painel')
await page.goto(BASE + '/')
await page.getByText('Carros na oficina').waitFor()
await shot('10-painel')

} catch (e) {
  await page.screenshot({ path: `${OUT}/erro.png`, fullPage: true }).catch(() => {})
  console.error('FALHOU:', e.message.split('\n')[0], '\n' + errors.join('\n'))
  await browser.close()
  process.exit(1)
}
await browser.close()
if (errors.length) {
  console.error('Erros no console:\n' + errors.join('\n'))
  process.exit(1)
}
console.log('E2E OK')
